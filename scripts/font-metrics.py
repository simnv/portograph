"""Extract numeric advances only; do not copy or redistribute font files."""
import json
from pathlib import Path
from fontTools.ttLib import TTFont

tables = {}
for weight, filename in [(400, "Arial.ttf"), (700, "Arial Bold.ttf")]:
    font = TTFont(Path("/System/Library/Fonts/Supplemental") / filename)
    cmap = font.getBestCmap()
    codepoints = [*range(32, 127), *range(160, 256), *range(0x400, 0x500)]
    tables[weight] = {
        "unitsPerEm": font["head"].unitsPerEm,
        "ascent": font["hhea"].ascent,
        "descent": -font["hhea"].descent,
        "lineGap": font["hhea"].lineGap,
        "advances": {chr(cp): font["hmtx"][cmap[cp]][0] for cp in codepoints if cp in cmap},
    }
header = """// Generated by uv run scripts/font-metrics.py. Numeric Arial glyph advances, no font outlines.
interface FontTable {
  unitsPerEm: number;
  ascent: number;
  descent: number;
  lineGap: number;
  advances: Readonly<Record<string, number>>;
}
export const FONT_METRICS: Readonly<Record<400 | 700, FontTable>> = """
destination = Path("src/text/font-metrics.ts")
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text(header + json.dumps(tables, ensure_ascii=False, indent=2) + ";\n")
print(f"Wrote {destination}: " + ", ".join(f"weight {w}: {len(t['advances'])} glyphs" for w, t in tables.items()))
